"""
Council Manager — EvaluationContext + CouncilMember + CouncilManager

Each council member receives the same structured context (tiered by model capacity)
and independently scores, ranks, and critiques all planner plans.
"""

import json
import logging
import time
import requests
from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import Dict, Any, List, Optional

logger = logging.getLogger(__name__)

# ─────────────────────────────────────────────────────────────────────────────
# Evaluation Context
# ─────────────────────────────────────────────────────────────────────────────

EVALUATOR_SYSTEM_PROMPT = """You are an expert evaluator in a MAPE-K autonomic computing system for Pegasus WMS workflows.

Your role is to evaluate repair plans generated by AI planning models against the original workflow failure analysis.

You will receive:
1. ANALYZER RESULT — the diagnosed problems, root causes, and confidence
2. PLANS TO EVALUATE — repair plans from different AI models
3. EVALUATION METRICS — criteria with weights to score each plan

Your task:
1. Score each plan on every metric (0.0 = worst, 1.0 = best)
2. Rank plans from best to worst
3. Flag contradictions: cases where a plan's approach conflicts with the analyzer's identified root cause
4. State your confidence in your own evaluation (0.0–1.0)
5. Write a brief reasoning summary

CRITICAL RULES:
- Score independently and honestly — do not favour any model
- A contradiction is when a plan fixes the wrong thing (e.g., plan adds a replica entry but root cause is a syntax error)
- Safety score must be 0.0 for any plan containing: rm -rf, dd, chmod 777, or irreversible destructive commands
- Output ONLY valid JSON — no markdown, no extra text

Required output structure:
{
  "scores": {
    "<plan_label>": {
      "<metric_name>": <0.0–1.0>,
      ...
    }
  },
  "ranking": ["<best_label>", "<second_label>", ...],
  "contradictions": [
    {"plan": "<label>", "issue": "<description of contradiction>"}
  ],
  "vetoes": [
    {"plan": "<label>", "reason": "<why this plan must be blocked>"}
  ],
  "reasoning": "<brief explanation of your evaluation decisions>",
  "confidence": <0.0–1.0>
}"""


class EvaluationContext:
    """
    Builds tiered prompts from the full evaluation input.
    Prompts are built once and cached — all council members share the same objects.
    """

    def __init__(
        self,
        workflow_id: str,
        analyzer_result: Dict[str, Any],
        plans: Dict[str, Any],
        metrics: List[Dict[str, Any]],
        catalogs: Dict[str, Any] = None,
        workflow_files: Dict[str, Any] = None,
        parent_error_analysis: Dict[str, Any] = None
    ):
        self.workflow_id = workflow_id
        self.analyzer_result = analyzer_result
        self.plans = plans
        self.metrics = metrics
        self.catalogs = catalogs or {}
        self.workflow_files = workflow_files or {}
        self.parent_error_analysis = parent_error_analysis or {}
        self._prompts: Dict[int, str] = {}

    def build_all_tiers(self):
        """Build and cache all tier prompts — called once before council runs"""
        self._prompts[1] = self._build_tier1()
        self._prompts[2] = self._build_tier2()
        self._prompts[3] = self._build_tier3()
        logger.info(
            f"Context tiers built — "
            f"T1:{len(self._prompts[1])} T2:{len(self._prompts[2])} T3:{len(self._prompts[3])} chars"
        )

    def get_prompt(self, tier: int) -> str:
        if not self._prompts:
            self.build_all_tiers()
        return self._prompts.get(tier, self._prompts[2])

    def _metrics_section(self, full: bool = True) -> str:
        lines = []
        for m in self.metrics:
            if full:
                lines.append(f"  - {m['name']} (weight={m['weight']}): {m['description']}")
            else:
                lines.append(f"  - {m['name']} (weight={m['weight']})")
        return "\n".join(lines)

    def _plans_section_full(self) -> str:
        return json.dumps(self.plans, indent=2)

    def _plans_section_compact(self) -> str:
        compact = {}
        for label, plan in self.plans.items():
            compact[label] = {
                "repair_steps": plan.get("repair_steps", []),
                "risk_level": plan.get("risk_level"),
                "confidence": plan.get("confidence")
            }
        return json.dumps(compact, indent=2)

    def _plans_section_essential(self) -> str:
        lines = []
        for label, plan in self.plans.items():
            steps = plan.get("repair_steps", [])
            step_list = "; ".join(
                s.get("command", s.get("action", str(s))) for s in steps[:5]
            )
            lines.append(f"{label}: {step_list}")
        return "\n".join(lines)

    def _analyzer_section_full(self) -> str:
        parts = [json.dumps(self.analyzer_result, indent=2)]
        if self.parent_error_analysis:
            parts.append("PARENT ERROR ANALYSIS:\n" + json.dumps(self.parent_error_analysis, indent=2))
        if self.catalogs:
            parts.append("CATALOGS:\n" + json.dumps(self.catalogs, indent=2))
        return "\n\n".join(parts)

    def _analyzer_section_compact(self) -> str:
        problems = self.analyzer_result.get("problems_and_solutions", [])
        confidence = self.analyzer_result.get("confidence", "unknown")
        return json.dumps({
            "problems_and_solutions": problems,
            "confidence": confidence,
            "parent_error": self.parent_error_analysis.get("parent_error") if self.parent_error_analysis else None
        }, indent=2)

    def _analyzer_section_essential(self) -> str:
        problems = self.analyzer_result.get("problems_and_solutions", [])[:3]
        lines = [f"Workflow: {self.workflow_id}", f"Top problems ({len(problems)}):"]
        for p in problems:
            lines.append(f"  - {p.get('problem', '')}")
        return "\n".join(lines)

    def _build_tier1(self) -> str:
        return f"""WORKFLOW EVALUATION REQUEST
Workflow ID: {self.workflow_id}

═══════════════════════════════════════════════════
ANALYZER RESULT (full)
═══════════════════════════════════════════════════
{self._analyzer_section_full()}

═══════════════════════════════════════════════════
PLANS TO EVALUATE (full)
═══════════════════════════════════════════════════
{self._plans_section_full()}

═══════════════════════════════════════════════════
EVALUATION METRICS
═══════════════════════════════════════════════════
{self._metrics_section(full=True)}

Plan labels to score and rank: {list(self.plans.keys())}

Provide your evaluation as JSON only."""

    def _build_tier2(self) -> str:
        return f"""WORKFLOW EVALUATION REQUEST
Workflow ID: {self.workflow_id}

ANALYZER RESULT:
{self._analyzer_section_compact()}

PLANS TO EVALUATE:
{self._plans_section_compact()}

EVALUATION METRICS:
{self._metrics_section(full=True)}

Plan labels to score and rank: {list(self.plans.keys())}

Provide your evaluation as JSON only."""

    def _build_tier3(self) -> str:
        return f"""WORKFLOW EVALUATION REQUEST
Workflow ID: {self.workflow_id}

ANALYZER RESULT:
{self._analyzer_section_essential()}

PLANS (essential):
{self._plans_section_essential()}

METRICS: {self._metrics_section(full=False)}

Plan labels: {list(self.plans.keys())}

Provide your evaluation as JSON only."""


