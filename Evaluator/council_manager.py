# Council Member
# ─────────────────────────────────────────────────────────────────────────────

class CouncilMember:
    """Single LLM-backed evaluator — calls Ollama or OpenAI"""

    def __init__(self, label: str, tier: int, config: Dict[str, Any]):
        self.label = label
        self.tier = tier
        self.provider, self.model = label.split("/", 1)
        self.ollama_url = config.get("ollama_url")
        self.openai_api_key = config.get("openai_api_key", "")
        self.openai_api_base = config.get("openai_api_base", "https://api.openai.com/v1")
        self.connection_timeout = config.get("connection_timeout", 300)

    def evaluate(self, context: EvaluationContext) -> Dict[str, Any]:
        """Run evaluation and return structured result"""
        prompt = context.get_prompt(self.tier)
        start = time.time()

        try:
            if self.provider == "ollama":
                raw = self._call_ollama(prompt)
            elif self.provider == "openai":
                raw = self._call_openai(prompt)
            else:
                raise ValueError(f"Unknown provider: {self.provider}")

            latency_ms = (time.time() - start) * 1000
            parsed = self._parse(raw)
            parsed["_member"] = self.label
            parsed["_tier"] = self.tier
            parsed["_latency_ms"] = round(latency_ms)
            parsed["_raw_response"] = raw
            parsed["_status"] = "success"
            return parsed

        except Exception as e:
            logger.error(f"Council member {self.label} failed: {e}")
            return {
                "_member": self.label,
                "_tier": self.tier,
                "_status": "failed",
                "_error": str(e),
                "scores": {},
                "ranking": [],
                "contradictions": [],
                "vetoes": [],
                "reasoning": "",
                "confidence": 0.0
            }

    def _call_ollama(self, prompt: str) -> str:
        full_prompt = f"{EVALUATOR_SYSTEM_PROMPT}\n\n{prompt}"
        payload = {
            "model": self.model,
            "prompt": full_prompt,
            "stream": True,
            "format": "json",
            "options": {"temperature": 0.1, "top_p": 0.9, "num_predict": 8000}
        }
        response = requests.post(
            self.ollama_url, json=payload,
            timeout=self.connection_timeout, stream=True
        )
        if response.status_code != 200:
            raise RuntimeError(f"Ollama HTTP {response.status_code}: {response.text[:200]}")
        result = ""
        for line in response.iter_lines():
            if line:
                chunk = json.loads(line.decode("utf-8"))
                result += chunk.get("response", "")
        return result

    def _call_openai(self, prompt: str) -> str:
        if not self.openai_api_key:
            raise RuntimeError("OpenAI API key not configured")
        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": EVALUATOR_SYSTEM_PROMPT},
                {"role": "user", "content": prompt}
            ],
            "temperature": 0.1,
            "response_format": {"type": "json_object"},
            "max_tokens": 8000
        }
        response = requests.post(
            f"{self.openai_api_base}/chat/completions",
            headers={
                "Authorization": f"Bearer {self.openai_api_key}",
                "Content-Type": "application/json"
            },
            json=payload,
            timeout=self.connection_timeout
        )
        if response.status_code != 200:
            raise RuntimeError(f"OpenAI HTTP {response.status_code}: {response.text[:200]}")
        return response.json()["choices"][0]["message"]["content"]

    def _parse(self, raw: str) -> Dict[str, Any]:
        """Parse LLM JSON output with fallback"""
        try:
            data = json.loads(raw)
        except json.JSONDecodeError:
            # Try to extract JSON block
            import re
            match = re.search(r'\{.*\}', raw, re.DOTALL)
            if match:
                data = json.loads(match.group())
            else:
                raise ValueError(f"Cannot parse LLM output as JSON: {raw[:200]}")

        return {
            "scores": data.get("scores", {}),
            "ranking": data.get("ranking", []),
            "contradictions": data.get("contradictions", []),
            "vetoes": data.get("vetoes", []),
            "reasoning": data.get("reasoning", ""),
            "confidence": float(data.get("confidence", 0.5))
        }


