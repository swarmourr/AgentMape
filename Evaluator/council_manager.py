# Council Manager
# ─────────────────────────────────────────────────────────────────────────────

class CouncilManager:
    """Spawns all council members in parallel and collects evaluations"""

    def __init__(self, config: Dict[str, Any]):
        self.members = [
            CouncilMember(m["label"], m.get("tier", 2), config)
            for m in config.get("council_models", [])
        ]
        self.tier_weights = {
            int(k): float(v)
            for k, v in config.get("tier_weights", {"1": 1.0, "2": 0.75, "3": 0.5}).items()
        }

        if not self.members:
            logger.warning("No council models configured — evaluator will have no members")

    def run_council(self, context: EvaluationContext) -> Dict[str, Dict[str, Any]]:
        """Run all members in parallel, return {label: evaluation}"""
        if not self.members:
            return {}

        logger.info(f"Running council with {len(self.members)} member(s)")
        results = {}

        with ThreadPoolExecutor(max_workers=len(self.members)) as executor:
            futures = {
                executor.submit(m.evaluate, context): m.label
                for m in self.members
            }
            for future in as_completed(futures):
                label = futures[future]
                try:
                    result = future.result()
                except Exception as e:
                    logger.error(f"Council member {label} thread error: {e}")
                    result = {
                        "_member": label, "_status": "failed", "_error": str(e),
                        "scores": {}, "ranking": [], "contradictions": [],
                        "vetoes": [], "reasoning": "", "confidence": 0.0
                    }
                results[label] = result
                status = "✓" if result.get("_status") == "success" else "✗"
                logger.info(f"  {status} {label}: confidence={result.get('confidence', 0):.2f}")

        return results
